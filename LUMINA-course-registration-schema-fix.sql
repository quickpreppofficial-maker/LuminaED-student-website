-- Idempotent support schema for LUMINA's course-registration workflow.
-- Run this before LUMINA-import-official-engineering-courses.sql.

create table if not exists public.department_aliases (
  alias text primary key,
  canonical_department text not null
);

alter table public.department_aliases enable row level security;
drop policy if exists "Authenticated users can read department aliases" on public.department_aliases;
create policy "Authenticated users can read department aliases"
  on public.department_aliases for select to authenticated using (true);

create table if not exists public.student_course_selections (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  course_id bigint not null references public.courses(id) on delete cascade,
  created_at timestamptz not null default now(),
  constraint student_course_selections_user_course_key unique (user_id, course_id)
);

create index if not exists student_course_selections_user_id_idx
  on public.student_course_selections(user_id);
create index if not exists student_course_selections_course_id_idx
  on public.student_course_selections(course_id);

alter table public.student_course_selections enable row level security;
drop policy if exists "Students can view their own course selections" on public.student_course_selections;
create policy "Students can view their own course selections"
  on public.student_course_selections for select to authenticated
  using (auth.uid() = user_id);
drop policy if exists "Students can insert their own course selections" on public.student_course_selections;
create policy "Students can insert their own course selections"
  on public.student_course_selections for insert to authenticated
  with check (auth.uid() = user_id);
drop policy if exists "Students can delete their own course selections" on public.student_course_selections;
create policy "Students can delete their own course selections"
  on public.student_course_selections for delete to authenticated
  using (auth.uid() = user_id);

-- Alias the source catalogue's ELE label to the existing canonical catalogue.
insert into public.department_aliases (alias, canonical_department) values
  ('Electrical / Electronics Engineering', 'Electrical Engineering'),
  ('Electrical/Electronics Engineering', 'Electrical Engineering'),
  ('Electrical and Electronics Engineering', 'Electrical Engineering'),
  ('Electrical & Electronics Engineering', 'Electrical Engineering')
on conflict (alias) do update set canonical_department = excluded.canonical_department;
