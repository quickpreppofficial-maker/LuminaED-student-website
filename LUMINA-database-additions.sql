create table if not exists public.student_academic_profiles (
  user_id uuid primary key references auth.users(id) on delete cascade,
  faculty text not null,
  department text not null,
  level text not null,
  updated_at timestamptz not null default now()
);

alter table public.student_academic_profiles enable row level security;
drop policy if exists "Students can view their own academic profile" on public.student_academic_profiles;
create policy "Students can view their own academic profile"
  on public.student_academic_profiles for select to authenticated
  using (auth.uid() = user_id);
drop policy if exists "Students can insert their own academic profile" on public.student_academic_profiles;
create policy "Students can insert their own academic profile"
  on public.student_academic_profiles for insert to authenticated
  with check (auth.uid() = user_id);
drop policy if exists "Students can update their own academic profile" on public.student_academic_profiles;
create policy "Students can update their own academic profile"
  on public.student_academic_profiles for update to authenticated
  using (auth.uid() = user_id) with check (auth.uid() = user_id);

create table if not exists public.courses (
  id bigint generated by default as identity primary key,
  faculty text not null,
  department text not null,
  level text not null,
  course_code text not null,
  course_title text not null,
  is_active boolean not null default true,
  created_at timestamptz not null default now(),
  unique (faculty, department, level, course_code)
);
alter table public.courses enable row level security;
drop policy if exists "Authenticated students can view active courses" on public.courses;
create policy "Authenticated students can view active courses"
  on public.courses for select to authenticated using (is_active = true);

create table if not exists public.test_attempts (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  course_code text not null,
  course_title text not null,
  score numeric(8,2) not null check (score >= 0),
  total_questions numeric(8,2) not null check (total_questions > 0),
  percentage numeric(6,2) not null check (percentage >= 0 and percentage <= 100),
  created_at timestamptz not null default now()
);
create index if not exists test_attempts_user_course_date_idx
  on public.test_attempts (user_id, course_code, created_at desc);
alter table public.test_attempts enable row level security;
drop policy if exists "Students can view their own test attempts" on public.test_attempts;
create policy "Students can view their own test attempts"
  on public.test_attempts for select to authenticated using (auth.uid() = user_id);
drop policy if exists "Students can insert their own test attempts" on public.test_attempts;
create policy "Students can insert their own test attempts"
  on public.test_attempts for insert to authenticated with check (auth.uid() = user_id);

